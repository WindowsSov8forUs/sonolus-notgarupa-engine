package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite ../resources.json from the engine's resource declarations")

// resourceListPath is the machine-readable list of the resource names the
// engine declares; resource generators and servers check items against it.
const resourceListPath = "../resources.json"

// ResourceList is the format of resources.json.
type ResourceList struct {
	Note     string        `json:"note"`
	Skin     ResourceNames `json:"skin"`
	Effect   ResourceNames `json:"effect"`
	Particle ResourceNames `json:"particle"`
}

// ResourceNames splits the declared names of one resource type: every item of
// the type (ordinary and #HABAHIRO) must provide Ordinary; the #HABAHIRO item
// must provide Habahiro in addition; Optional names are checked with Exists()
// and mark per-item properties.
type ResourceNames struct {
	Ordinary []string `json:"ordinary"`
	Habahiro []string `json:"habahiro,omitempty"`
	Optional []string `json:"optional,omitempty"`
}

const resourceListNote = "Resource names declared by the engine (engine/*.go). Every item of a type must provide `ordinary`; the #HABAHIRO item must provide `habahiro` in addition; `optional` names are existence markers of per-item properties. Generated by `go test ./engine -run TestResourceList -update`; do not edit."

// Fields named *Opt declare optional existence markers.
//
// habahiroField reports whether a resource struct field holds names that only
// the #HABAHIRO item provides: the skin's Haba* fields and the particles'
// width variants (*W).
func habahiroField(constructor, field string) bool {
	switch constructor {
	case "SkinSprite":
		return strings.HasPrefix(field, "Haba")
	case "ParticleEffect":
		return strings.HasSuffix(field, "W")
	}
	return false
}

// declaredResources collects the string literals passed to the sonolus
// resource constructors in the engine sources, grouped by the composite
// literal field they are assigned to.
func declaredResources(t *testing.T) ResourceList {
	t.Helper()
	fset := token.NewFileSet()
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	type set struct{ ordinary, habahiro, optional map[string]bool }
	sets := map[string]*set{}
	for _, c := range []string{"SkinSprite", "EffectClip", "ParticleEffect"} {
		sets[c] = &set{map[string]bool{}, map[string]bool{}, map[string]bool{}}
	}
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		var stack []ast.Node
		ast.Inspect(f, func(n ast.Node) bool {
			if n == nil {
				stack = stack[:len(stack)-1]
				return true
			}
			stack = append(stack, n)
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			if pkg, ok := sel.X.(*ast.Ident); !ok || pkg.Name != "sonolus" || sets[sel.Sel.Name] == nil {
				return true
			}
			lit, ok := call.Args[0].(*ast.BasicLit)
			if len(call.Args) != 1 || !ok || lit.Kind != token.STRING {
				t.Errorf("%s: %s needs a string literal", fset.Position(call.Pos()), sel.Sel.Name)
				return true
			}
			value, err := strconv.Unquote(lit.Value)
			if err != nil {
				t.Fatal(err)
			}
			field := ""
			for i := len(stack) - 1; i >= 0 && field == ""; i-- {
				if kv, ok := stack[i].(*ast.KeyValueExpr); ok {
					if key, ok := kv.Key.(*ast.Ident); ok {
						field = key.Name
					}
				}
			}
			s := sets[sel.Sel.Name]
			if strings.HasSuffix(field, "Opt") {
				s.optional[value] = true
			} else if habahiroField(sel.Sel.Name, field) {
				s.habahiro[value] = true
			} else {
				s.ordinary[value] = true
			}
			return true
		})
	}
	names := func(c string) ResourceNames {
		var r ResourceNames
		for v := range sets[c].ordinary {
			r.Ordinary = append(r.Ordinary, v)
		}
		for v := range sets[c].habahiro {
			if !sets[c].ordinary[v] {
				r.Habahiro = append(r.Habahiro, v)
			}
		}
		for v := range sets[c].optional {
			r.Optional = append(r.Optional, v)
		}
		slices.Sort(r.Ordinary)
		slices.Sort(r.Habahiro)
		slices.Sort(r.Optional)
		return r
	}
	return ResourceList{Note: resourceListNote, Skin: names("SkinSprite"), Effect: names("EffectClip"), Particle: names("ParticleEffect")}
}

// TestResourceList keeps resources.json in step with the declarations.
func TestResourceList(t *testing.T) {
	list := declaredResources(t)
	// The HABAHIRO skin sprites are exactly the habahiro/ names.
	for _, n := range list.Skin.Ordinary {
		if strings.HasPrefix(n, "habahiro/") {
			t.Errorf("skin sprite %s is HABAHIRO-only but declared outside a Haba* field", n)
		}
	}
	for _, n := range list.Skin.Habahiro {
		if !strings.HasPrefix(n, "habahiro/") {
			t.Errorf("skin sprite %s of a Haba* field lacks the habahiro/ prefix", n)
		}
	}
	data, err := json.MarshalIndent(list, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	data = append(data, '\n')
	if *update {
		if err := os.WriteFile(resourceListPath, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	current, err := os.ReadFile(resourceListPath)
	if err != nil {
		t.Fatalf("%v (run go test ./engine -run TestResourceList -update)", err)
	}
	if !bytes.Equal(current, data) {
		t.Fatalf("%s is out of date: run go test ./engine -run TestResourceList -update", resourceListPath)
	}
}
